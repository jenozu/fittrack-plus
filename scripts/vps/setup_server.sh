#!/usr/bin/env bash
# One-time setup of a fresh Ubuntu 22.04/24.04 VPS for FitTrack+.
#
#   curl -fsSL https://raw.githubusercontent.com/jenozu/fittrack-plus/main/scripts/vps/setup_server.sh -o setup.sh
#   sudo DOMAIN=fit.example.com EMAIL=you@example.com bash setup.sh
#
# No domain yet? Run without DOMAIN/EMAIL: the site is served over plain HTTP on the
# server's IP and certbot is skipped. (Phones only allow the camera and "Add to Home
# Screen" on HTTPS, so re-run with DOMAIN/EMAIL once you have one.)
# With a domain, point its DNS A record at this server's IP first.
#
# Safe to re-run. Existing .env, database and passwords are kept; nginx/systemd files
# are rewritten (the old ones are saved as *.bak).
set -euo pipefail

DOMAIN="${DOMAIN:-}"   # empty = IP-only, HTTP-only mode
EMAIL="${EMAIL:-}"
[[ -z "$DOMAIN" || -n "$EMAIL" ]] || { echo "Set EMAIL too (HTTPS certificate expiry notices)." >&2; exit 1; }
REPO_URL="${REPO_URL:-https://github.com/jenozu/fittrack-plus.git}"
BRANCH="${BRANCH:-main}"
APP_DIR="${APP_DIR:-/var/www/fittrack-plus}"
APP_USER="${APP_USER:-fittrack}"
DB_NAME="${DB_NAME:-fittrack_db}"
DB_USER="${DB_USER:-fittrack}"
# nginx listen address. Behind another proxy (e.g. Traefik owning :80/:443) use LISTEN=127.0.0.1:8090
# and route the hostname to it, plus ORIGIN_OVERRIDE=https://<host> for CORS.
LISTEN="${LISTEN:-80}"
FOOD_DIR="/var/lib/fittrack/fooddata"

[[ $EUID -eq 0 ]] || { echo "Run with sudo." >&2; exit 1; }
. /etc/os-release
[[ "$ID" == "ubuntu" ]] || echo "Warning: written for Ubuntu, found $ID. Continuing anyway."

if [[ -n "$DOMAIN" ]]; then
  SITE_HOST="$DOMAIN"; ORIGIN="https://$DOMAIN"
else
  SITE_HOST="$(curl -fsS -4 https://ifconfig.me || true)"
  [[ -n "$SITE_HOST" ]] || { echo "Could not detect the server IP; set DOMAIN or SITE_HOST." >&2; exit 1; }
  ORIGIN="http://$SITE_HOST"
fi
ORIGIN="${ORIGIN_OVERRIDE:-$ORIGIN}"

say() { echo; echo "==> $*"; }
backup_file() { [[ -f "$1" ]] && cp -f "$1" "$1.bak" || true; }

say "Installing system packages"
export DEBIAN_FRONTEND=noninteractive
apt-get update -q
apt-get install -y -q git curl unzip ca-certificates build-essential \
  postgresql postgresql-contrib python3 python3-venv python3-dev libpq-dev \
  nginx certbot python3-certbot-nginx ufw

if ! command -v node >/dev/null || [[ "$(node -v | sed 's/v\([0-9]*\).*/\1/')" -lt 20 ]]; then
  say "Installing Node.js 22"
  curl -fsSL https://deb.nodesource.com/setup_22.x | bash -
  apt-get install -y -q nodejs
fi

# Small VPSes run out of memory building the frontend or importing food data.
MEM_MB=$(awk '/MemTotal/ {print int($2/1024)}' /proc/meminfo)
if [[ $MEM_MB -lt 3000 ]] && ! swapon --show | grep -q .; then
  say "Adding a 2 GB swap file (only ${MEM_MB} MB RAM)"
  fallocate -l 2G /swapfile && chmod 600 /swapfile && mkswap /swapfile && swapon /swapfile
  grep -q '^/swapfile' /etc/fstab || echo '/swapfile none swap sw 0 0' >> /etc/fstab
fi

say "App user and code"
id "$APP_USER" >/dev/null 2>&1 || useradd --system --create-home --home-dir "/home/$APP_USER" --shell /bin/bash "$APP_USER"
mkdir -p "$(dirname "$APP_DIR")" "$FOOD_DIR"
if [[ ! -d "$APP_DIR/.git" ]]; then
  if [[ -d "$APP_DIR" ]]; then
    mv "$APP_DIR" "$APP_DIR.old-$(date +%s)"
    echo "Moved an existing non-git $APP_DIR aside."
  fi
  git clone --branch "$BRANCH" "$REPO_URL" "$APP_DIR"
fi
chown -R "$APP_USER:$APP_USER" "$APP_DIR" "$(dirname "$FOOD_DIR")"
git config --system --add safe.directory "$APP_DIR" || true

say "PostgreSQL"
systemctl enable --now postgresql
ENV_FILE="$APP_DIR/backend/.env"
if [[ -f "$ENV_FILE" ]] && grep -q '^DATABASE_URL=' "$ENV_FILE"; then
  echo "Keeping existing $ENV_FILE"
else
  DB_PASS="$(openssl rand -hex 24)"
  if sudo -u postgres psql -tAc "SELECT 1 FROM pg_roles WHERE rolname='$DB_USER'" | grep -q 1; then
    sudo -u postgres psql -qc "ALTER ROLE $DB_USER WITH LOGIN PASSWORD '$DB_PASS'"
  else
    sudo -u postgres psql -qc "CREATE ROLE $DB_USER WITH LOGIN PASSWORD '$DB_PASS'"
  fi
  sudo -u postgres psql -tAc "SELECT 1 FROM pg_database WHERE datname='$DB_NAME'" | grep -q 1 \
    || sudo -u postgres createdb -O "$DB_USER" "$DB_NAME"
  cat > "$ENV_FILE" <<ENV
# Generated by setup_server.sh on $(date -I). Never commit this file.
DATABASE_URL=postgresql://$DB_USER:$DB_PASS@localhost:5432/$DB_NAME
SECRET_KEY=$(openssl rand -hex 32)
ALLOWED_ORIGINS=$ORIGIN
OFF_USER_AGENT="FitTrackPlus/1.0${EMAIL:+ ($EMAIL)}"
USDA_API_KEY=
OPENAI_API_KEY=
ENV
fi
chown "$APP_USER:$APP_USER" "$ENV_FILE"
chmod 600 "$ENV_FILE"
# Extensions need a superuser; create them once here so the app user never needs to.
sudo -u postgres psql -q -d "$DB_NAME" -c "CREATE EXTENSION IF NOT EXISTS pg_trgm; CREATE EXTENSION IF NOT EXISTS unaccent;"
sudo -u postgres psql -q -d "$DB_NAME" -c "GRANT ALL ON SCHEMA public TO $DB_USER;"

say "Python environment"
sudo -u "$APP_USER" bash -c "cd '$APP_DIR/backend' && python3 -m venv venv && venv/bin/pip install -q --upgrade pip && venv/bin/pip install -q -r requirements.txt"

say "systemd service: fittrack-backend"
UNIT=/etc/systemd/system/fittrack-backend.service
backup_file "$UNIT"
cat > "$UNIT" <<UNITFILE
[Unit]
Description=FitTrack+ API (FastAPI/uvicorn)
After=network.target postgresql.service
Requires=postgresql.service

[Service]
User=$APP_USER
Group=$APP_USER
WorkingDirectory=$APP_DIR/backend
EnvironmentFile=$ENV_FILE
ExecStart=$APP_DIR/backend/venv/bin/uvicorn main:app --host 127.0.0.1 --port 8000 --workers 2 --proxy-headers --forwarded-allow-ips 127.0.0.1
Restart=always
RestartSec=3
NoNewPrivileges=true
PrivateTmp=true

[Install]
WantedBy=multi-user.target
UNITFILE
systemctl daemon-reload
systemctl enable fittrack-backend

say "nginx"
SITE=/etc/nginx/sites-available/fittrack
backup_file "$SITE"
cat > "$SITE" <<NGINX
server {
    listen $LISTEN;
$([[ "$LISTEN" == 80 ]] && echo "    listen [::]:80;")
    server_name ${DOMAIN:-_};

    root $APP_DIR/frontend/dist;
    index index.html;
    client_max_body_size 10m;

    gzip on;
    gzip_types text/css application/javascript application/json image/svg+xml application/manifest+json;

    # API: https://$DOMAIN/api/food/search -> http://127.0.0.1:8000/food/search
    location /api/ {
        proxy_pass http://127.0.0.1:8000/;
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto \$scheme;
        proxy_read_timeout 60s;
    }

    # The service worker and manifest must never be cached, or app updates never arrive.
    location = /sw.js                { add_header Cache-Control "no-cache"; try_files \$uri =404; }
    location = /manifest.webmanifest { add_header Cache-Control "no-cache"; try_files \$uri =404; }
    location = /index.html           { add_header Cache-Control "no-cache"; }

    # Hashed build assets can be cached forever.
    location /assets/ { add_header Cache-Control "public, max-age=31536000, immutable"; try_files \$uri =404; }

    # Single-page app: every other path is handled by React Router.
    location / { try_files \$uri \$uri/ /index.html; }
}
NGINX
ln -sf "$SITE" /etc/nginx/sites-enabled/fittrack
rm -f /etc/nginx/sites-enabled/default
mkdir -p "$APP_DIR/frontend/dist"
[[ -f "$APP_DIR/frontend/dist/index.html" ]] || echo "<h1>FitTrack+ is being set up</h1>" > "$APP_DIR/frontend/dist/index.html"
chown -R "$APP_USER:$APP_USER" "$APP_DIR/frontend/dist"
nginx -t
systemctl reload nginx

say "Firewall"
ufw allow OpenSSH >/dev/null
ufw allow 'Nginx Full' >/dev/null
ufw --force enable >/dev/null
ufw status | sed 's/^/  /'

say "HTTPS certificate"
SERVER_IP="$(curl -fsS -4 https://ifconfig.me || true)"
DNS_IP="$([[ -n "$DOMAIN" ]] && getent ahostsv4 "$DOMAIN" | awk 'NR==1{print $1}' || true)"
if [[ -z "$DOMAIN" ]]; then
  echo "  No DOMAIN set: skipping certbot, serving HTTP only at $ORIGIN"
elif [[ -n "$SERVER_IP" && "$SERVER_IP" == "$DNS_IP" ]]; then
  certbot --nginx -d "$DOMAIN" --non-interactive --agree-tos -m "$EMAIL" --redirect
else
  echo "  $DOMAIN resolves to '${DNS_IP:-nothing}', this server is '${SERVER_IP:-unknown}'."
  echo "  Fix the DNS A record, wait a few minutes, then run:"
  echo "    sudo certbot --nginx -d $DOMAIN -m $EMAIL --agree-tos --redirect"
fi

say "Nightly database backup (03:15)"
mkdir -p /var/backups/fittrack && chown postgres:postgres /var/backups/fittrack
cat > /etc/cron.d/fittrack-backup <<CRON
15 3 * * * postgres DB_NAME=$DB_NAME bash $APP_DIR/scripts/vps/backup_db.sh >> /var/log/fittrack-backup.log 2>&1
CRON
touch /var/log/fittrack-backup.log && chown postgres /var/log/fittrack-backup.log

say "Done"
cat <<NEXT
Next steps (all on this server):
  1. Deploy the app:        sudo bash $APP_DIR/scripts/vps/deploy.sh
  2. Get the food data:     sudo -u $APP_USER bash $APP_DIR/scripts/food/download_food_data.sh
  3. Import it:             sudo -u $APP_USER bash $APP_DIR/scripts/food/import_food_data.sh
  4. Open $ORIGIN on your phone and register.
NEXT
